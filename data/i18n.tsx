export type TranslationDict = typeof t[Lang];

interface I18nContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  tx: TranslationDict;
}

const I18nContext = createContext<I18nContextType>({
  lang: 'en',
  setLang: () => {},
  tx: t.en,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');
  
  // Load saved preference after mount (client-side only)
  useState(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('canyouhearme-lang') as Lang | null;
      if (saved && t[saved]) {
        setLangState(saved);
      }
    }
    return undefined;
  });
  
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    if (typeof window !== 'undefined') {
      localStorage.setItem('canyouhearme-lang', l);
    }
  }, []);

  return (
    <I18nContext.Provider value={{ lang, setLang, tx: t[lang] }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

// Helper to get translated label with fallback to English
export function getTx(lang: Lang, key: keyof TranslationDict): string {
  return (t[lang][key] || t.en[key]) as string;
}
